// Generates TypeScript and Swift types for every socket event from the JSON Schemas.
//   npm run generate   writes generated/SocketEvents.ts and generated/SocketEvents.swift
//   npm run check      exits 1 if the committed files are out of date (used by CI)

import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const sharedDir = join(dirname(fileURLToPath(import.meta.url)), "..");
// Run quicktype's entry file with node directly, so it also works on Windows (no .bin shim).
const quicktype = join(sharedDir, "node_modules", "quicktype", "dist", "index.js");
const checkOnly = process.argv.includes("--check");

// Relative, sorted paths keep the output identical on every machine.
const schemas = ["client", "server"].flatMap((dir) =>
  readdirSync(join(sharedDir, "schemas", dir))
    .filter((f) => f.endsWith(".schema.json"))
    .sort()
    .map((f) => `schemas/${dir}/${f}`),
);

const targets = [
  {
    file: "SocketEvents.ts",
    // Unions instead of enums: the web app's tsconfig uses erasableSyntaxOnly.
    args: ["--lang", "typescript", "--just-types", "--prefer-unions"],
  },
  {
    file: "SocketEvents.swift",
    args: ["--lang", "swift", "--struct-or-class", "struct", "--access-level", "public", "--protocol", "equatable"],
  },
];

const outDir = checkOnly ? mkdtempSync(join(tmpdir(), "teraphobia-types-")) : join(sharedDir, "generated");
mkdirSync(outDir, { recursive: true });

let stale = [];
try {
  for (const { file, args } of targets) {
    const out = join(outDir, file);
    execFileSync(process.execPath, [quicktype, "--src-lang", "schema", ...args, "--out", out, ...schemas], {
      cwd: sharedDir,
      stdio: ["ignore", "ignore", "inherit"],
    });
    // Header so nobody edits the output by hand.
    const body = readFileSync(out, "utf8");
    writeFileSync(out, `// Generated by shared/scripts/generate.mjs from shared/schemas. Do not edit.\n// Run \`npm run generate\` in shared/ after changing a schema.\n\n${body}`);

    if (checkOnly) {
      let committed = "";
      try {
        committed = readFileSync(join(sharedDir, "generated", file), "utf8");
      } catch {}
      if (committed !== readFileSync(out, "utf8")) stale.push(`generated/${file}`);
    } else {
      console.log(`wrote generated/${file}`);
    }
  }
} finally {
  if (checkOnly) rmSync(outDir, { recursive: true, force: true });
}

if (stale.length) {
  console.error(`Out of date: ${stale.join(", ")}\nRun \`npm run generate\` in shared/ and commit the result.`);
  process.exit(1);
}
if (checkOnly) console.log("Generated types are up to date.");
